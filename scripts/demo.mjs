#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
// Demo: a sample repo, scripted fake agents (no subscription usage), the local tracker, an
// Obsidian-style vault and the graphify code graph, all under a durable demo data dir.
//
//   pnpm demo            start (or resume) the demo daemon
//   pnpm demo --reset    wipe the demo data dir first
//
// Scenario markers in an issue description drive the fake agents:
//   [fake:network-fail] [fake:network-fail-once] [fake:usage-limit] [fake:ask-human]
//   [fake:hang] [fake:slow] [fake:no-handoff] [fake:out-of-scope] [fake:overage]
import { execFileSync, spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = process.platform === 'darwin' ? path.join(os.homedir(), 'Library', 'Application Support') : path.join(os.homedir(), '.local', 'state');
const DATA = process.env.ACC_DEMO_DIR ?? path.join(base, 'AgentControlCenter-demo');
const PORT = Number(process.env.ACC_PORT ?? 7318);

if (process.argv.includes('--reset')) fs.rmSync(DATA, { recursive: true, force: true });
fs.mkdirSync(DATA, { recursive: true });

const repo = path.join(DATA, 'sample-repo');
if (!fs.existsSync(path.join(repo, '.git'))) {
  fs.cpSync(path.join(ROOT, 'examples', 'sample-repo'), repo, { recursive: true });
  const git = (...a) => execFileSync('git', a, { cwd: repo, stdio: 'ignore', env: { ...process.env, GIT_AUTHOR_NAME: 'demo', GIT_AUTHOR_EMAIL: 'demo@example.com', GIT_COMMITTER_NAME: 'demo', GIT_COMMITTER_EMAIL: 'demo@example.com' } });
  git('init', '-q', '-b', 'main');
  git('add', '-A');
  git('commit', '-q', '-m', 'initial');
  git('branch', 'integration');
}

// Explicit unsandboxed mode is confined to this generated disposable demo repository.
fs.writeFileSync(path.join(repo, '.git', 'one-connect-disposable-host-fixture'), 'HOST FIXTURE (unsandboxed; disposable tests/demo only)\n');

const vault = path.join(DATA, 'vault');
const notes = path.join(vault, 'Projects', 'sample-app');
if (!fs.existsSync(notes)) {
  fs.mkdirSync(notes, { recursive: true });
  fs.writeFileSync(path.join(notes, 'Architecture.md'), '# Architecture\n\n`src/math.js` holds the arithmetic helpers; tests live in `test/` and run with `node --test`.\nKeep functions pure; no I/O in `src/`.\n');
}

const bin = (n) => path.join(ROOT, 'examples', 'fake-agent', 'bin', n);
let hasGraphify = true;
try {
  execFileSync('graphify', ['--help'], { stdio: 'ignore' });
} catch {
  hasGraphify = false;
}

const config = `# Generated by scripts/demo.mjs: fake agents, zero subscription usage.
project:
  name: sample-app
  repo: ${JSON.stringify(repo)}
  integration_branch: integration
  protected_branches: [main]
  checks: { test: "node --test" }
  check_runtime: { mode: host-fixture, fixture_repo: ${JSON.stringify(repo)} }
tracker: { type: local, key_prefix: DEMO }
policies:
  zero_extra_spend: true
  newest_model_rule: true
  stall: { no_event_minutes: 2, approval_pending_minutes: 1 }
  idle_alert_minutes: 1
knowledge:
  vault: ${JSON.stringify(vault)}
  folder: Agent Control Center
  context_folders: [Projects/sample-app]
${hasGraphify ? 'graphify:\n  enabled: true\n' : ''}agents:
  - { id: lead, name: "Claude Code", subscription: "Claude Max", role: lead, adapter: claude-headless, binary: ${JSON.stringify(bin('claude'))}, mode: coordinator-only, model: newest, model_family: opus }
  - { id: codex, name: "Codex", subscription: "ChatGPT Plus", role: engineer, adapter: codex-cli, binary: ${JSON.stringify(bin('codex'))}, model: newest, effort: high }
  - { id: cursor, name: "Cursor", subscription: "Cursor Pro", role: engineer, adapter: cursor-agent-cli, binary: ${JSON.stringify(bin('cursor-agent'))}, model: newest, model_family: claude-opus, effort: high }
  - { id: ag, name: "Antigravity", subscription: "Google AI Pro", role: engineer, adapter: relay }
server: { port: ${PORT} }
`;
const cfgFile = path.join(DATA, 'control-center.yaml');
fs.writeFileSync(cfgFile, config);

console.log('HOST FIXTURE: project checks run unsandboxed on disposable demo source; real projects require Docker.');
console.log(`demo data: ${DATA}`);
console.log('sign a browser in any time with: pnpm demo:open   (or: pnpm acc open)');
const child = spawn(process.execPath, ['--disable-warning=ExperimentalWarning', path.join(ROOT, 'packages', 'daemon', 'src', 'cli.ts'), 'daemon', '--config', cfgFile], {
  stdio: 'inherit',
  env: { ...process.env, ACC_DEMO_FIXTURES: '1', ACC_DATA_DIR: path.join(DATA, 'state'), FAKE_STEP_MS: process.env.FAKE_STEP_MS ?? '900', FAKE_SLOW_MS: process.env.FAKE_SLOW_MS ?? '20000', FAKE_TOKEN_MS: process.env.FAKE_TOKEN_MS ?? '45' },
});
const stop = (sig) => child.kill(sig);
process.on('SIGINT', () => stop('SIGINT'));
process.on('SIGTERM', () => stop('SIGTERM'));
child.on('exit', (code) => process.exit(code ?? 0));
