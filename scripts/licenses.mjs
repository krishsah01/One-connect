#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
// Third-party license inventory + compatibility gate.
//   node scripts/licenses.mjs --write   regenerate THIRD_PARTY_NOTICES.md
//   node scripts/licenses.mjs --check   fail if a dependency's license is incompatible with ours
//                                       or THIRD_PARTY_NOTICES.md is out of date (CI)
// The project license comes from the root package.json (single source of truth).
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { nativeDependencies } from './native-dependencies.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'THIRD_PARTY_NOTICES.md');
const own = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).license;
const policy = JSON.parse(fs.readFileSync(path.join(ROOT, 'license-policy.json'), 'utf8'));

function list(kind) {
  const out = execFileSync('pnpm', ['licenses', 'list', '--json', kind === 'prod' ? '--prod' : '--dev'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  const byLicense = JSON.parse(out || '{}');
  const pkgs = [];
  for (const [license, entries] of Object.entries(byLicense)) {
    for (const e of entries) if (!e.name.startsWith('@acc/')) pkgs.push({ name: e.name, versions: e.versions, license, homepage: e.homepage ?? '' });
  }
  return pkgs.sort((a, b) => a.name.localeCompare(b.name));
}

/** SPDX expression check: "(MIT OR Apache-2.0)" passes if any alternative is allowed. */
function allowed(license, pkgName) {
  const exception = policy.exceptions.find((x) => x.package === pkgName);
  if (exception) return { ok: true, why: `exception: ${exception.reason}` };
  const allow = policy.compatible[own];
  if (!allow) return { ok: false, why: `no compatibility list for project license ${own} in license-policy.json` };
  // Cargo also contains legacy slash-separated alternatives. AND requires every term;
  // grouping is preserved so permissive alternatives cannot mask an incompatible clause.
  const tokens = license.replaceAll('/', ' OR ').match(/\(|\)|AND|OR|[\w.+-]+/g) ?? [];
  let pos = 0;
  function term() {
    if (tokens[pos] === '(') { pos++; const v = or(); if (tokens[pos++] !== ')') throw new Error('Unclosed expression'); return v; }
    return allow.includes(tokens[pos++]);
  }
  function and() { let v = term(); while (tokens[pos] === 'AND') { pos++; const r = term(); v = v && r; } return v; }
  function or() { let v = and(); while (tokens[pos] === 'OR') { pos++; const r = and(); v = v || r; } return v; }
  let ok = false;
  try { ok = or() && pos === tokens.length; } catch { /* unknown expression is refused */ }
  return { ok, why: ok ? license : `${license} is not in the reviewed allowlist for ${own}` };
}

const designerRoot=path.join(ROOT,'packages/daemon/resources/designer');
const designer=JSON.parse(fs.readFileSync(path.join(designerRoot,'manifest.json'),'utf8'));
for(const s of designer.skills) for(const f of s.files) {
  const content=fs.readFileSync(path.join(designerRoot,'skills',s.id,f.path));
  if(createHash('sha256').update(content).digest('hex')!==f.sha256)throw new Error(`Designer resource hash differs from its reviewed manifest: ${s.id}/${f.path}`);
  if(!allowed(s.license,s.id).ok)throw new Error(`Designer skill ${s.id}: unreviewed license ${s.license}`);
}
function render(prod, dev, native) {
  const lines = [
    '# Third-party notices',
    '',
    `<!-- Generated by scripts/licenses.mjs from the dependency tree. Do not edit by hand. -->`,
    '',
    `One Connect is licensed under ${own}. It bundles or depends on the packages below; each is used under its own license. Vendor agent CLIs (Claude Code, Codex, Cursor, …) are **not** bundled: users install them from the vendors.`,
    '',
    '## Runtime dependencies',
    '',
    '| Package | Version | License |',
    '|---|---|---|',
    ...prod.map((p) => `| ${p.homepage ? `[${p.name}](${p.homepage})` : p.name} | ${p.versions.join(', ')} | ${p.license} |`),
    '',
    '## Development-only dependencies (not distributed)',
    '',
    '| Package | Version | License |',
    '|---|---|---|',
    ...dev.map((p) => `| ${p.name} | ${p.versions.join(', ')} | ${p.license} |`),
    '',
    '## Native Mac runtime and build dependencies',
    '',
    'This conservative inventory includes build-time crates. Each crate retains its own license. The app includes original license notices in the bundled engine’s `native-notices/` directory and unchanged source for MPL-2.0 crates in `native-sources/`. Source can also be obtained from the versioned crate links below. MPL-covered source is provided under MPL-2.0; the application’s Apache-2.0 license does not replace those terms.',
    '',
    '| Crate / source | Version | License |',
    '|---|---|---|',
    ...native.map(p => `| [${p.name}](https://crates.io/crates/${p.name}/${p.version}) | ${p.version} | ${p.license ?? 'UNKNOWN'} |`),
    '',
    'The packaged Node runtime includes its full third-party license text at `runtime/LICENSE`.',
    '',
    '## Pinned designer resources',
    '',
    `Selected Open Design resources are pinned at [${designer.openDesignCommit}](${designer.openDesignSource}/tree/${designer.openDesignCommit}). Its Apache-2.0 license is retained in packages/daemon/resources/designer/OPEN_DESIGN_LICENSE. Individual upstream MIT notices are retained beside their skills and references. No vendor executable, hosted account, or media API is bundled or enabled by these resources.`,
    '',
    '| Resource | Revision | License |',
    '|---|---|---|',
    ...designer.skills.map(s=>`| ${s.source.startsWith('https://')?`[${s.name}](${s.source})`:s.name} | ${s.version} | ${s.license} |`),
    '',
    ...designer.skills.flatMap(s=>s.files.filter(f=>/(^|\/)LICENSE$/.test(f.path)).flatMap(f=>[`### ${s.name} upstream notice`,'',fs.readFileSync(path.join(designerRoot,'skills',s.id,f.path),'utf8').trim(),''])),
  ];
  return lines.join('\n');
}

const prod = list('prod');
const dev = list('dev');
const native = nativeDependencies();
const bad = prod.map((p) => ({ p, r: allowed(p.license, p.name) })).filter((x) => !x.r.ok);
const devBad = dev.map((p) => ({ p, r: allowed(p.license, p.name) })).filter((x) => !x.r.ok);
const nativeBad = native.filter(p => !allowed(p.license ?? 'UNKNOWN', p.name).ok);
const text = render(prod, dev, native);

if (process.argv.includes('--write')) {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${prod.length} runtime, ${dev.length} dev packages`);
}
if (devBad.length) console.warn(`note: dev-only packages outside the allowlist (not distributed):\n${devBad.map((x) => `  - ${x.p.name}: ${x.r.why}`).join('\n')}`);
if (nativeBad.length) {
  console.error(`✗ native dependencies outside the ${own} allowlist:\n${nativeBad.map(p => `  - ${p.name}@${p.version}: ${p.license ?? 'UNKNOWN'}`).join('\n')}`);
  process.exit(1);
}
if (bad.length) {
  console.error(`✗ runtime dependencies with licenses incompatible with ${own}:\n${bad.map((x) => `  - ${x.p.name}@${x.p.versions.join(',')}: ${x.r.why}`).join('\n')}\nAdd a reviewed exception to license-policy.json only after checking the license.`);
  process.exit(1);
}
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('✗ THIRD_PARTY_NOTICES.md is out of date: run `pnpm license:notices`');
    process.exit(1);
  }
  console.log(`✓ ${prod.length} runtime dependencies compatible with ${own}; notices up to date`);
}
