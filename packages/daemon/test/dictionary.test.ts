import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { afterEach,describe,expect,it } from 'vitest';
import type { DocAnswer } from '@acc/core';
import { extractProject } from '../src/context/extract-project.ts';
import { git,makeRepo,makeConfig,startDaemon,tmpDir,type Harness } from './helpers.ts';
let h:Harness|null=null;
afterEach(async()=>{await h?.close();h=null;delete process.env.DICTIONARY_TEST_SECRET;});
const sha=(repo:string)=>git(repo,'rev-parse','HEAD');
const commit=(repo:string)=>{git(repo,'add','-A');git(repo,'commit','-qm','source fixture');return sha(repo);};
describe('Dictionary project intake',()=>{
  it('extracts an exact commit without dirty files, symlinks, secrets, generated files, binary data or executing scripts',async()=>{
    const repo=makeRepo(),outside=tmpDir('outside');
    fs.writeFileSync(path.join(outside,'private.md'),'private outside project');
    fs.mkdirSync(path.join(repo,'node_modules'),{recursive:true});fs.mkdirSync(path.join(repo,'.aws'),{recursive:true});
    fs.writeFileSync(path.join(repo,'.env'),'OPENAI_API_KEY=secret');fs.writeFileSync(path.join(repo,'.aws','config'),'private access configuration');
    fs.writeFileSync(path.join(repo,'node_modules','leak.ts'),'private dependency');
    fs.symlinkSync(path.join(outside,'private.md'),path.join(repo,'linked.md'));
    fs.writeFileSync(path.join(repo,'binary.ts'),Buffer.from([65,0,66]));
    fs.writeFileSync(path.join(repo,'bad\nname.md'),'invalid path');
    fs.writeFileSync(path.join(repo,'tokens.css'),':root { --accent: teal; }');
    fs.writeFileSync(path.join(repo,'README.md'),'# Authentic source\nCommitted auth policy secret-to-redact.');
    fs.writeFileSync(path.join(repo,'package.json'),JSON.stringify({name:'intake',dependencies:{zod:'4'},scripts:{test:`touch ${path.join(outside,'executed')}`}}));
    const revision=commit(repo);
    fs.writeFileSync(path.join(repo,'README.md'),'DIRTY version');fs.writeFileSync(path.join(repo,'untracked.md'),'new untracked');
    const result=await extractProject(repo,revision,s=>s.replaceAll('secret-to-redact','[REDACTED]'));
    expect(result.files.find(f=>f.path==='README.md')?.content).toContain('Authentic source');
    expect(result.files.find(f=>f.path==='README.md')?.content).toContain('[REDACTED]');
    expect(result.files.some(f=>['.env','.aws/config','node_modules/leak.ts','linked.md','binary.ts','bad\nname.md','untracked.md'].includes(f.path))).toBe(false);
    expect(result.files.some(f=>f.path==='tokens.css')).toBe(true);
    expect(result.packages[0]).toMatchObject({name:'intake',dependencies:['zod'],scripts:{test:expect.stringContaining('touch')}});
    expect(fs.existsSync(path.join(outside,'executed'))).toBe(false);
    const file=result.files.find(f=>f.path==='README.md')!;
    expect(file.hash).toBe(createHash('sha256').update(file.content).digest('hex'));
    await expect(extractProject(repo,'HEAD',s=>s)).rejects.toThrow(/exact commit/);
    await expect(extractProject(repo,'--upload',s=>s)).rejects.toThrow(/exact commit/);
    await expect(extractProject(repo,git(repo,'rev-parse','HEAD^{tree}'),s=>s)).rejects.toThrow(/Git read failed/);
  });
  it('bounds source file count and file bytes, and flags partial extraction',async()=>{
    const repo=makeRepo();fs.mkdirSync(path.join(repo,'many'));
    for(let i=0;i<502;i++)fs.writeFileSync(path.join(repo,'many',`${i}.ts`),'export const value = 1;');
    fs.writeFileSync(path.join(repo,'oversize.md'),'x'.repeat(65537));
    fs.writeFileSync(path.join(repo,'malformed.json'),'{');
    // Explicit limits: the defaults are larger (see DEFAULT_LIMITS); this checks the bounding behavior.
    const r=await extractProject(repo,commit(repo),s=>s,{files:500});
    expect(r.files).toHaveLength(500);expect(r.truncated).toBe(true);expect(r.files.some(f=>f.path==='oversize.md')).toBe(false);
    expect(r.files.some(f=>f.path==='malformed.json')).toBe(true);
  },30000);
  it('automatically syncs redacted notes, local vectors and graph to one revision, cites source lines, updates and survives restart',async()=>{
    const repo=makeRepo(),vault=tmpDir('answer-vault');
    fs.mkdirSync(path.join(vault,'Personal'));fs.writeFileSync(path.join(vault,'Personal','Diary.md'),'Unrelated private authentication diary.');
    fs.writeFileSync(path.join(repo,'README.md'),'# Project\nThe zeta session expires every 47 minutes. DICTIONARY-PRIVATE-VALUE');
    const revision=commit(repo);git(repo,'branch','-f','integration',revision);
    process.env.DICTIONARY_TEST_SECRET='DICTIONARY-PRIVATE-VALUE';
    const cfg=makeConfig(repo,{knowledge:{vault,folder:'One Connect',obsidian_cli:'off',search:{semantic:true,embedding_model:'local-fixture'}},graphify:{enabled:true,binary:path.join(import.meta.dirname,'fixtures','fake-graphify.mjs')},policies:{redact_env:['DICTIONARY_TEST_SECRET']}});
    const localFetch=async(url:string,init?:RequestInit)=>{
      expect(new URL(url).hostname).toBe('127.0.0.1');
      if(url.endsWith('/api/tags'))return Response.json({models:[{name:'local-fixture:latest',digest:'test-v1'}]});
      if(url.endsWith('/api/show'))return Response.json({capabilities:['embedding']});
      if(url.endsWith('/api/embed'))return Response.json({embeddings:JSON.parse(String(init?.body)).input.map(()=>[1,0])});
      throw new Error('unexpected endpoint');
    };
    h=await startDaemon(cfg,{probe:false,fetch:localFetch});
    expect(h.d.context.answer.status).toMatchObject({state:'ready',revision,notesRevision:revision,embeddingsRevision:revision,graphRevision:revision});
    const result=h.d.context.answer.cite(await h.d.context.docs!.ask('zeta session 47 minutes'));
    const citation=result.citations.find(c=>c.projectSource?.path==='README.md')!;
    expect(citation.projectSource).toMatchObject({revision,line:1,endLine:2});
    expect(JSON.stringify(result)).not.toContain('DICTIONARY-PRIVATE-VALUE');
    expect(JSON.stringify(result)).not.toContain('Unrelated private');
    const sourceDir=h.d.context.graph!.dir;
    expect(fs.readFileSync(path.join(sourceDir,'README.md'),'utf8')).toContain('[REDACTED:');
    expect(fs.readFileSync(path.join(sourceDir,'README.md'),'utf8')).not.toContain('DICTIONARY-PRIVATE-VALUE');
    fs.writeFileSync(path.join(repo,'README.md'),'# Updated project\nA tau login lasts 53 minutes.');
    const next=commit(repo);git(repo,'branch','-f','integration',next);
    await h.d.context.answer.refresh(false);
    expect(h.d.context.answer.status).toMatchObject({revision:next,notesRevision:next,embeddingsRevision:next,graphRevision:next});
    expect((await h.d.context.docs!.search('zeta')).citations.every(c=>!c.excerpt.includes('zeta'))).toBe(true);
    expect(h.d.context.docs!.db.prepare("SELECT count(*) AS n FROM chunks WHERE content LIKE '%zeta%'").get()).toMatchObject({n:0});
    const token=fs.readFileSync(path.join(h.d.paths.secrets,'install-token'),'utf8').trim();
    const response=await fetch(h.url+'/api/context/docs/ask',{method:'POST',headers:{authorization:`Bearer ${token}`,'content-type':'application/json'},body:JSON.stringify({query:'tau login 53 minutes'})});
    expect(response.status).toBe(200);expect((await response.json() as DocAnswer).citations.some(c=>c.projectSource?.revision===next)).toBe(true);
    const dataDir=h.dataDir;await h.close();h=null;
    h=await startDaemon(cfg,{probe:false,fetch:localFetch,dataDir});
    expect(h.d.context.answer.status.state).toBe('ready');expect(h.d.context.answer.status.revision).toBe(next);
    const note=h.d.context.vault!.notePath('Dictionary',createHash('sha256').update('README.md').digest('hex')+'.md');
    fs.writeFileSync(path.join(vault,note),'# Edited note\nCannot claim the old source SHA.');
    const forged=h.d.context.answer.cite({...result,citations:[{...citation,excerpt:'forged'}]});
    expect(forged.citations[0].projectSource).toBeUndefined();
    await h.d.context.answer.refresh(false);
    expect(h.d.context.answer.cite(await h.d.context.docs!.search('tau login')).citations.some(c=>c.projectSource?.revision===next)).toBe(true);
  },30000);
  it('provides a private default vault and honest partial status without a model or Graphify',async()=>{
    h=await startDaemon(makeConfig(makeRepo()),{probe:false,server:false});
    expect(h.d.context.privateVault).toBe(true);
    expect(h.d.context.vault!.root.startsWith(h.dataDir)).toBe(true);
    expect(h.d.context.answer.status).toMatchObject({state:'partial',embeddingsRevision:null,graphRevision:null});
    expect(h.d.context.answer.status.error).toContain('Semantic search is off');
    expect(h.d.egress.log).toEqual([]);
  });
});
