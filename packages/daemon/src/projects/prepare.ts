// Turn an inspected repository into a project configuration. A repository's own
// control-center.yaml is used only when it binds this exact folder; otherwise a generated
// configuration is written to app-owned storage, never into the user's repository.
import fs from 'node:fs';
import path from 'node:path';
import YAML from 'yaml';
import { parseConfig } from '@acc/core';
import { writePrivate } from '../paths.ts';
import { inspectProject, ProjectIntakeError, type ProjectInspection } from './inspect.ts';
import { sha256 } from '../util/hash.ts';

export interface PreparedProject { config: string; generated: boolean; inspection: ProjectInspection }

export function generatedConfig(i: ProjectInspection, name = i.name): string {
  const protectedBranch = i.git.branch && i.git.branch !== 'integration' ? i.git.branch : 'main';
  const raw = {
    project: {
      name,
      repo: i.path,
      ...(i.compose ? { docker_project: i.compose.project } : {}),
      integration_branch: 'integration',
      protected_branches: [protectedBranch],
      checks: Object.fromEntries(i.checks.map(c => [c.name, c.command])),
      // Declared checks are listed but not run automatically until the owner requires them.
      required_checks: [],
    },
    tracker: { type: 'local', key_prefix: name.replace(/[^a-z]/gi, '').slice(0, 4).toUpperCase() || 'LOC' },
    agents: [
      { id: 'lead', name: 'Claude Code', role: 'lead', adapter: 'claude-headless', mode: 'coordinator-only', model: 'newest', model_family: 'opus' },
      { id: 'codex', name: 'Codex', role: 'engineer', adapter: 'codex-cli', model: 'newest', effort: 'high' },
      { id: 'cursor', name: 'Cursor', role: 'engineer', adapter: 'cursor-agent-cli', model: 'newest', on_demand: false },
    ],
  };
  parseConfig(raw);
  const header = [
    '# Generated by One Connect for one repository. Edit freely; the repository binding must stay exact.',
    `# Declared checks were read from ${[...new Set(i.checks.map(c => c.source))].join(', ') || 'no manifests'} and have not been run.`,
    '# Agents use official subscription CLIs. Paid API fallback and on-demand usage stay off.',
  ];
  return `${header.join('\n')}\n${YAML.stringify(raw)}`;
}

export function generatedConfigPath(configDir: string, repo: string): string {
  return path.join(configDir, `${sha256(repo).slice(0, 32)}.yaml`);
}

export async function prepareProject(dir: string, configDir: string, o: { name?: string } = {}): Promise<PreparedProject> {
  const inspection = await inspectProject(dir);
  if (inspection.git.state === 'not_git') throw new ProjectIntakeError(`${inspection.intake.message} Use the “Initialize Git” onboarding step first.`);
  if (inspection.git.state === 'not_root') throw new ProjectIntakeError(inspection.intake.message);
  if (inspection.config.existing) {
    if (!inspection.config.bound) throw new ProjectIntakeError(`Refusing ${path.basename(inspection.config.existing)}: ${inspection.config.error}`);
    return { config: inspection.config.existing, generated: false, inspection };
  }
  if (!path.isAbsolute(configDir)) throw new ProjectIntakeError('Configuration directory must be absolute');
  fs.mkdirSync(configDir, { recursive: true, mode: 0o700 });
  const file = generatedConfigPath(fs.realpathSync(configDir), inspection.path);
  if (fs.existsSync(file)) {
    const existing = YAML.parse(fs.readFileSync(file, 'utf8')) as { project?: { repo?: string } };
    if (existing?.project?.repo !== inspection.path) throw new ProjectIntakeError('A generated configuration with this identity is bound to another folder.');
    return { config: file, generated: true, inspection };
  }
  writePrivate(file, generatedConfig(inspection, o.name?.trim() || inspection.name));
  return { config: file, generated: true, inspection };
}
