// Local development databases. Postgres runs in this project's Compose namespace with a
// project-scoped named volume, a loopback-only port and a password that exists only in a 0600
// secret file. SQLite is a 0600 file in app data. Neither path can address a remote database.
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import YAML from 'yaml';
import { writePrivate } from '../paths.ts';

export interface PostgresSpec { kind: 'postgres'; service: string; database: string; user: string; version: string; port: number }
export interface SqliteSpec { kind: 'sqlite'; name: string }
export type DatabaseSpec = PostgresSpec | SqliteSpec;
export interface DatabaseRecord { spec: DatabaseSpec; createdAt: string }

const IDENT = /^[a-z][a-z0-9_]{0,62}$/;
const SERVICE = /^[a-z][a-z0-9-]{0,62}$/;

export class DatabaseSpecError extends Error {}

export function parseDatabaseSpec(input: unknown): DatabaseSpec {
  const o = (input ?? {}) as Record<string, unknown>;
  const refuseProd = (label: string, v: string) => { if (/prod/i.test(v)) throw new DatabaseSpecError(`${label} must not name a production database. This wizard creates local development databases only.`); };
  if (o.kind === 'sqlite') {
    const name = String(o.name ?? 'dev');
    if (!/^[a-z][a-z0-9_-]{0,62}$/.test(name)) throw new DatabaseSpecError('SQLite name: lowercase letters, digits, dash and underscore.');
    refuseProd('Name', name);
    return { kind: 'sqlite', name };
  }
  if (o.kind !== 'postgres') throw new DatabaseSpecError('Choose Postgres or SQLite.');
  const spec: PostgresSpec = { kind: 'postgres', service: String(o.service ?? 'db'), database: String(o.database ?? 'app'), user: String(o.user ?? 'app'), version: String(o.version ?? '16-alpine'), port: Number(o.port ?? 5432) };
  if (!SERVICE.test(spec.service)) throw new DatabaseSpecError('Service name: lowercase letters, digits and dashes.');
  if (!IDENT.test(spec.database) || !IDENT.test(spec.user)) throw new DatabaseSpecError('Database and user: lowercase letters, digits and underscores, starting with a letter.');
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/.test(spec.version)) throw new DatabaseSpecError('Postgres image tag is not valid.');
  if (!Number.isInteger(spec.port) || spec.port < 1024 || spec.port > 65535) throw new DatabaseSpecError('Host port must be between 1024 and 65535.');
  for (const [label, v] of [['Service', spec.service], ['Database', spec.database], ['User', spec.user]] as const) refuseProd(label, v);
  return spec;
}

export const postgresImage = (s: PostgresSpec) => `postgres:${s.version}`;
export const volumeName = (s: PostgresSpec) => `${s.service}-data`;

export class DatabaseFiles {
  readonly dir: string;
  constructor(dataRoot: string) { this.dir = path.join(dataRoot, 'environment'); }
  get composeFile() { return path.join(this.dir, 'compose.one-connect.yaml'); }
  secretFile(service: string) { return path.join(this.dir, 'secrets', `${service}-password`); }
  sqliteFile(name: string) { return path.join(this.dir, 'sqlite', `${name}.sqlite`); }

  /** Compose text for every wizard-created Postgres service. Contains a secret file path, never a password. */
  compose(project: string, records: DatabaseRecord[]): string {
    const pg = records.map(r => r.spec).filter((s): s is PostgresSpec => s.kind === 'postgres');
    const doc = {
      services: Object.fromEntries(pg.map(s => [s.service, {
        image: postgresImage(s),
        environment: { POSTGRES_DB: s.database, POSTGRES_USER: s.user, POSTGRES_PASSWORD_FILE: `/run/secrets/${s.service}_password` },
        secrets: [`${s.service}_password`],
        ports: [`127.0.0.1:${s.port}:5432`],
        volumes: [`${volumeName(s)}:/var/lib/postgresql/data`],
        healthcheck: { test: ['CMD-SHELL', `pg_isready -U ${s.user} -d ${s.database}`], interval: '5s', timeout: '3s', retries: 12, start_period: '5s' },
        labels: { 'dev.oneconnect.managed': 'true', 'dev.oneconnect.project': project },
      }])),
      volumes: Object.fromEntries(pg.map(s => [volumeName(s), { labels: { 'dev.oneconnect.managed': 'true', 'dev.oneconnect.project': project } }])),
      secrets: Object.fromEntries(pg.map(s => [`${s.service}_password`, { file: this.secretFile(s.service) }])),
    };
    return `# Generated by One Connect for Compose project ${project}. Local development only.\n# The password is read from a 0600 secret file and never appears here.\n${YAML.stringify(doc)}`;
  }

  /** Create or keep the service password. Existing passwords are reused so the data volume stays usable. */
  ensureSecret(service: string): string {
    const file = this.secretFile(service);
    try {
      const existing = fs.readFileSync(file, 'utf8').trim();
      if (existing.length >= 24) { fs.chmodSync(file, 0o600); return existing; }
    } catch { /* create */ }
    const password = randomBytes(24).toString('base64url');
    fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
    fs.chmodSync(path.dirname(file), 0o700);
    writePrivate(file, password);
    return password;
  }

  readSecret(service: string): string | null {
    try { return fs.readFileSync(this.secretFile(service), 'utf8').trim() || null; } catch { return null; }
  }

  writeCompose(project: string, records: DatabaseRecord[]) {
    fs.mkdirSync(this.dir, { recursive: true, mode: 0o700 });
    writePrivate(this.composeFile, this.compose(project, records));
  }

  createSqlite(name: string): string {
    const file = this.sqliteFile(name);
    fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
    const db = new DatabaseSync(file);
    db.exec('PRAGMA journal_mode=WAL; PRAGMA user_version');
    db.close();
    fs.chmodSync(file, 0o600);
    return file;
  }
}
